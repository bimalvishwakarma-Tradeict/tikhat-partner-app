/**
 * GET /api/v1/admin/reports/financial-year?year=2024
 */
export async function adminFinancialYearReport(req, res) {
  try {
    const fy = getFinancialYearBounds(req.query.year);
    const format = parseFormat(req.query.format);
    const [capitalRows, revenueRows] = await Promise.all([
      buildCapitalReportRows(fy.from, fy.to),
      buildRevenueReportRows(fy.from, fy.to),
    ]);

    const capitalTotal = capitalRows.reduce((s, r) => s + r.amount, 0);
    const revenueTotal = revenueRows.reduce((s, r) => s + r.amount, 0);
    const adminName = req.user?.name || 'Admin';

    if (format === 'excel') {
      const workbookRows = [
        ...capitalRows.map((r) => ({
          section: 'Capital',
          date_formatted: r.date_formatted,
          transaction_id: r.transaction_id,
          investor_name: r.investor_name,
          type: r.type,
          amount: r.amount,
          status: r.status,
        })),
        ...revenueRows.map((r) => ({
          section: 'Revenue',
          date_formatted: r.date_formatted,
          transaction_id: r.transaction_id,
          investor_name: r.investor_name,
          type: r.credit_type,
          amount: r.amount,
          status: 'credited',
        })),
      ];

      const buffer = await generateExcelBuffer({
        sheetName: fy.label,
        title: `Financial Year Report ${fy.label}`,
        fromDate: fy.from,
        toDate: fy.to,
        columns: [
          { key: 'section', label: 'Section', width: 80 },
          { key: 'date_formatted', label: 'Date', width: 80 },
          { key: 'transaction_id', label: 'Transaction ID', width: 140 },
          { key: 'investor_name', label: 'Partner', width: 140 },
          { key: 'type', label: 'Type', width: 100 },
          { key: 'amount', label: 'Amount', width: 80 },
          { key: 'status', label: 'Status', width: 80 },
        ],
        rows: workbookRows,
        meta: {
          'Capital Total': formatCurrency(capitalTotal),
          'Revenue Total': formatCurrency(revenueTotal),
          'Generated by': adminName,
        },
      });
      return sendFile(res, buffer, `fy-report-${fy.year}`, 'excel');
    }

    const combined = [
      ...capitalRows.map((r) => ({
        date_formatted: r.date_formatted,
        section: 'Capital',
        detail: `${r.investor_name} · ${r.type}`,
        amount_formatted: r.amount_formatted,
      })),
      ...revenueRows.map((r) => ({
        date_formatted: r.date_formatted,
        section: 'Revenue',
        detail: `${r.investor_name} · ${r.credit_type}`,
        amount_formatted: r.amount_formatted,
      })),
    ];

    const buffer = await generatePdfBuffer({
      title: `Financial Year Report ${fy.label}`,
      subtitle: `${REPORT_BRAND.COMPANY_NAME} · April ${fy.year} – March ${fy.year + 1}`,
      fromDate: fy.from,
      toDate: fy.to,
      columns: [
        { key: 'date_formatted', label: 'Date', width: 70 },
        { key: 'section', label: 'Section', width: 70 },
        { key: 'detail', label: 'Detail', width: 250 },
        { key: 'amount_formatted', label: 'Amount', width: 90 },
      ],
      rows: combined,
      summaryLines: [
        `Capital total: ${formatCurrency(capitalTotal)}`,
        `Revenue total: ${formatCurrency(revenueTotal)}`,
      ],
      footerLeft: `Generated ${formatDate(new Date())} · Admin: ${adminName}`,
      footerRight: REPORT_BRAND.DOMAIN,
    });

    return sendFile(res, buffer, `fy-report-${fy.year}`, 'pdf');
  } catch (error) {
    return handleError(res, error, 'adminFinancialYearReport');
  }
}
