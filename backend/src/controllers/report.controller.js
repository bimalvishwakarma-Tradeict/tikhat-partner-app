const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/**
 * @param {import('express').Response} res
 * @param {Error} error
 * @param {string} context
 */
function handleError(res, error, context) {
  if (error?.code === 'VALIDATION_ERROR' || error?.status === 400) {
    return res.status(400).json({
      success: false,
      message: error.message || 'Validation failed',
      error: 'VALIDATION_ERROR',
    });
  }

  logger.error(`[Report] ${context}: ${error.message}`, { error });
  return res.status(500).json({
    success: false,
    message: 'Report generation failed',
    error: 'INTERNAL_ERROR',
  });
}

/**
 * @param {unknown} value
 * @returns {'pdf' | 'excel'}
 */
function parseFormat(value) {
  const raw = String(value || 'pdf').toLowerCase().trim();
  if (raw === 'excel' || raw === 'xlsx') {
    return 'excel';
  }
  return 'pdf';
}

/**
 * @param {import('express').Response} res
 * @param {Buffer} buffer
 * @param {string} filename
 * @param {'pdf' | 'excel'} format
 */
function sendFile(res, buffer, filename, format) {
  if (format === 'excel') {
    res.setHeader(
      'Content-Type',
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
    );
    res.setHeader(
      'Content-Disposition',
      `attachment; filename="${filename}.xlsx"`
    );
  } else {
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader(
      'Content-Disposition',
      `attachment; filename="${filename}.pdf"`
    );
  }
  res.setHeader('Content-Length', String(buffer.length));
  return res.status(200).send(buffer);
}

/**
 * GET /api/v1/admin/reports/investor/:id/statement
 */
export async function adminInvestorStatement(req, res) {
  try {
    const { id } = req.params;
    if (!UUID_RE.test(id)) {
      return res.status(400).json({
        success: false,
        message: 'Invalid investor id',
        error: 'VALIDATION_ERROR',
      });
    }

    const fromDate = parseReportDate(req.query.from, 'from');
    const toDate = parseReportDate(req.query.to, 'to');
    if (fromDate > toDate) {
      return res.status(400).json({
        success: false,
        message: 'from must be on or before to',
        error: 'VALIDATION_ERROR',
      });
    }

    const format = parseFormat(req.query.format);
    const investor = await findInvestorForReport(id);
    if (!investor || investor.is_deleted) {
      return res.status(404).json({
        success: false,
        message: 'Investor not found',
        error: 'NOT_FOUND',
      });
    }

    const statement = await buildInvestorStatement(id, fromDate, toDate);
    const adminName = req.user?.name || 'Admin';
    const columns = [
      { key: 'date_formatted', label: 'Date', width: 70 },
      { key: 'description', label: 'Description', width: 220 },
      { key: 'credit_formatted', label: 'Credit', width: 80 },
      { key: 'debit_formatted', label: 'Debit', width: 80 },
      { key: 'balance_formatted', label: 'Balance', width: 90 },
    ];

    const excelColumns = [
      { key: 'date_formatted', label: 'Date', width: 80 },
      { key: 'description', label: 'Description', width: 240 },
      { key: 'credit', label: 'Credit', width: 80 },
      { key: 'debit', label: 'Debit', width: 80 },
      { key: 'balance', label: 'Balance', width: 90 },
    ];

    if (format === 'excel') {
      const buffer = await generateExcelBuffer({
        sheetName: 'Statement',
        title: 'Investor Transaction Statement',
        fromDate,
        toDate,
        columns: excelColumns,
        rows: statement.rows,
        meta: {
          Partner: investor.full_name,
          Email: investor.email,
          'Opening Balance': statement.openingBalanceFormatted,
          'Closing Balance': statement.closingBalanceFormatted,
          'Generated by': adminName,
        },
      });
      return sendFile(
        res,
        buffer,
        `statement-${investor.full_name.replace(/\s+/g, '-')}-${fromDate}-${toDate}`,
        'excel'
      );
    }

    const buffer = await generatePdfBuffer({
      title: 'Investor Transaction Statement',
      subtitle: `${REPORT_BRAND.COMPANY_NAME} · ${REPORT_BRAND.DOMAIN}`,
      investorName: investor.full_name,
      fromDate,
      toDate,
      columns,
      rows: statement.rows,
      summaryLines: [
        `Opening balance: ${statement.openingBalanceFormatted}`,
        `Closing balance: ${statement.closingBalanceFormatted}`,
      ],
      footerLeft: `Generated ${formatDate(new Date())} · Admin: ${adminName}`,
      footerRight: REPORT_BRAND.DOMAIN,
    });

    return sendFile(
      res,
      buffer,
      `statement-${fromDate}-${toDate}`,
      'pdf'
    );
  } catch (error) {
    return handleError(res, error, 'adminInvestorStatement');
  }
}

